"""Verify World Tile collision meshes and physical face IDs through Blender save/reload."""

import os
import sys
import tempfile
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, REPO)

import bpy  # noqa: E402

import adm_blender  # noqa: E402

FAILS = []


def check(condition, message):
    print(("  ok   " if condition else "  FAIL ") + message, flush=True)
    if not condition:
        FAILS.append(message)


def run(tmp, path):
    from adm_blender.core import constants as K
    from adm_blender.core.container import read_container
    from adm_blender.blender.export_adm import ExportOptions, ModelExporter
    from adm_blender.blender.import_adm import ImportOptions, ModelImporter

    with open(path, "rb") as stream:
        source_doc = read_container(stream.read(), K.ADM_MAGIC)[0]
    source_materials = source_doc.get("physicalMaterials", [])
    source_ids = [
        ident
        for collider in source_doc.get("colliders", [])
        if collider.get("shape") == "MESH"
        for primitive in source_doc["meshes"][collider["mesh"]]["primitives"]
        for ident in (primitive.get("extensions", {})
                      .get(K.PHYSICAL_SURFACES_EXT, {}).get("faceMaterials", []))
    ]
    check(bool(source_materials) and bool(source_ids), "generated World Tile ADM contains physical face assignments")
    bpy.ops.wm.read_homefile(use_empty=True)
    root = ModelImporter(bpy.context, path, ImportOptions(weld=False)).run()
    root_name = root.name
    collider = next((obj for obj in bpy.data.objects
                     if obj.adm.adm_type == "COLLIDER" and obj.adm.collider_shape == "MESH"), None)
    check(collider is not None, "World Tile MESH collider imports")
    check(root.adm.physical_materials[0].name == source_materials[0]["id"]
          and abs(root.adm.physical_materials[0].friction - source_materials[0]["friction"]) < 1e-6,
          "physical material identity and coefficients import")
    attr = collider.data.attributes.get("adm_physical_material_id") if collider else None
    ids = [] if attr is None else [item.value.decode("utf-8") if isinstance(item.value, bytes) else item.value
                                   for item in attr.data]
    check(bool(ids) and set(filter(None, ids)) == set(source_ids)
          and any(not ident for ident in ids),
          "assigned and unassigned triangles import into the collision FACE attribute")

    blend_path = os.path.join(tmp, "roundtrip.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    bpy.ops.wm.open_mainfile(filepath=blend_path)
    root = bpy.data.objects.get(root_name)
    _data, report = ModelExporter(bpy.context, root, ExportOptions(vertex_controls=True)).export()
    check(report is not None and report.ok, "saved World Tile scene re-exports as valid ADM")
    if report is not None and report.ok:
        ids_after = [
            ident
            for mesh in report.doc["meshes"]
            for primitive in mesh.get("primitives", [])
            for ident in (primitive.get("extensions", {})
                          .get("ADM_physical_surfaces_v1", {}).get("faceMaterials", []))
        ]
        check(bool(ids_after) and sorted(ids_after) == sorted(source_ids),
              "stable physical face IDs survive Blender save/reload and ADM re-export")
        collision = next(item for item in report.doc["colliders"] if item.get("shape") == "MESH")
        collision_primitives = report.doc["meshes"][collision["mesh"]]["primitives"]
        check(any(K.PHYSICAL_SURFACES_EXT in primitive.get("extensions", {})
                  for primitive in collision_primitives)
              and any(K.PHYSICAL_SURFACES_EXT not in primitive.get("extensions", {})
                      for primitive in collision_primitives),
              "assigned and unassigned collision faces remain separate on re-export")
        check(report.doc.get("physicalMaterials", [])[0]["id"] == source_materials[0]["id"],
              "physical-material reference survives Blender save/reload")


def main():
    adm_blender.register()
    try:
        path = os.environ.get("AWT_COLLISION_ADM")
        if not path or not os.path.isfile(path):
            raise ValueError("Set AWT_COLLISION_ADM to an ADM tile generated by World Tile with physical paint.")
        with tempfile.TemporaryDirectory(prefix="awt_collision_blender_") as tmp:
            run(tmp, path)
    finally:
        adm_blender.unregister()
    if FAILS:
        raise SystemExit(f"{len(FAILS)} World Tile collision Blender check(s) failed")
    print("All World Tile collision Blender checks passed.", flush=True)


if __name__ == "__main__":
    try:
        main()
    except Exception:
        traceback.print_exc()
        raise
